# 이 파일에서 읽어야 할 문법·계산
# [[[10,10]],...] 형태는 OpenCV 윤곽선에서 흔히 사용하는 N×1×2 배열이다.
# m["m00"]는 딕셔너리에서 면적 모멘트를 꺼낸다. m10/m00와 m01/m00는 각각 x·y 중심이다.
# None은 중심을 계산할 수 없음을 뜻한다. (0,0)을 대신 쓰면 원점에서 정상 검출한 것으로 오해할 수 있다.

# 상세 주석판 — 들여쓰기는 실행 범위를, # 뒤의 글은 실행되지 않는 설명을 뜻한다.
# 좌표 (x,y)는 (열,행), NumPy 인덱스는 [행,열]이다. 컬러 배열은 H×W×3이다.
# = 는 대입, == 는 값 비교, is None은 결과 없음 검사다. 함수 호출은 이름(인자) 형태다.
"""m00=0과 정상 사각형의 중심 계산을 비교한다. 카메라가 필요 없다."""
# cv2는 OpenCV의 파이썬 모듈명이다. 설치할 때의 패키지 이름은 opencv-python이다.
import cv2
# NumPy를 np라는 별명으로 불러온다. 영상은 숫자를 담은 다차원 배열이다.
import numpy as np

# def로 재사용할 함수를 정의한다. 괄호 안은 입력 인자이며 = 뒤 값은 생략 시 기본값이다. 들여쓴 본문은 호출할 때 실행된다.
def center(contour):
    # moments(윤곽선)는 모멘트 딕셔너리를 반환한다. 중심은 m10/m00, m01/m00이며 m00=0이면 나눗셈이 불가능하다.
    m = cv2.moments(contour)
    # 조건이 참일 때만 들여쓴 코드를 실행한다. and는 모두 참, or는 하나 이상 참, not은 참/거짓 반전이다.
    if m['m00'] == 0:
        # 계산 결과를 호출한 곳으로 돌려주고 함수를 끝낸다. 쉼표로 여러 값을 반환하면 튜플로 묶인다.
        return None
    # 계산 결과를 호출한 곳으로 돌려주고 함수를 끝낸다. 쉼표로 여러 값을 반환하면 튜플로 묶인다.
    return (m['m10']/m['m00'],m['m01']/m['m00'])

# 파일을 직접 실행할 때만 아래 블록을 수행한다. 다른 파일에서 import하면 이 블록은 실행하지 않는다.
if __name__ == '__main__':
    # 리스트를 NumPy 배열로 만든다. uint8은 0~255 정수이며 int32는 부호 있는 32비트 정수다.
    line=np.array([[[10,10]],[[20,20]],[[30,30]]],np.int32)
    # 리스트를 NumPy 배열로 만든다. uint8은 0~255 정수이며 int32는 부호 있는 32비트 정수다.
    square=np.array([[[10,10]],[[30,10]],[[30,30]],[[10,30]]],np.int32)
    # for는 목록/범위의 값을 하나씩 꺼내 반복한다. 쉼표로 묶인 변수에는 각 원소를 나누어 대입한다.
    for name,c in [('일직선: 면적 0',line),('사각형',square)]:
        # moments(윤곽선)는 모멘트 딕셔너리를 반환한다. 중심은 m10/m00, m01/m00이며 m00=0이면 나눗셈이 불가능하다.
        print(name,'m00=',cv2.moments(c)['m00'],'center=',center(c))
    # 조건이 참인지 검사하는 검증문이다. 거짓이면 AssertionError가 발생한다. 카메라의 정상 동작을 대신 보장하지는 않는다.
    assert center(line) is None
    # 조건이 참인지 검사하는 검증문이다. 거짓이면 AssertionError가 발생한다. 카메라의 정상 동작을 대신 보장하지는 않는다.
    assert center(square)==(20.,20.)
